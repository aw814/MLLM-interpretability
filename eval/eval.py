from google import genai
from google.genai import types
from google.genai.errors import APIError, ClientError
from pathlib import Path
from typing import Dict, Tuple
import time
import csv
import re  # Import the regex module
from pydantic import BaseModel, Field

# --- Pydantic Models for Prompts ---
class JudgeFields(BaseModel):
    """Fields passed to the judge model."""
    context: str = Field(description="The ground truth content/context for the question.")
    question: str = Field(description="The question asked.")
    answer: str = Field(description="The answer generated by the model being evaluated.")

def qa_user_message(question: str) -> types.Content:
    """Creates the message for the Question Answering model."""
    text_content = (
        f"Answer the following question based on your general knowledge. Be concise but accurate.\n\n"
        f"Question: {question}"
    )
    return types.Content(
        role="user",
        parts=[types.Part(text=text_content)],
    )

def judge_user_message(fields: JudgeFields) -> types.Content:
    """
    Creates the user message for the Judge model, including strong system instructions.
    """
    
    # 1. System/Role Instruction (Integrated into the user text) - STRONGER LANGUAGE
    system_instruction = (
        "YOU ARE AN EXPERT EVALUATOR. Your sole task is to determine if the 'Answer' correctly and truthfully answers the 'Question' "
        "based **ONLY** on the provided 'Context'. "
        "YOUR RESPONSE MUST BE ONE WORD ONLY: 'YES' or 'NO'. DO NOT provide any explanation, punctuation, or other text."
    )
    
    # 2. User Content/Task
    user_content = (
        f"Context: {fields.context}\n\n"
        f"Question: {fields.question}\n\n"
        f"Answer: {fields.answer}"
    )
    
    # Combine the instruction and content
    combined_text = f"{system_instruction}\n\n---\n\n{user_content}"
    
    return types.Content(
        role="user",
        parts=[types.Part(text=combined_text)],
    )
